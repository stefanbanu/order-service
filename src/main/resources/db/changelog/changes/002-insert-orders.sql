-- The contextFilter:seed tag is what keeps these rows out of the tests. application.yaml
-- activates the "seed" context; src/test/resources/application.yaml activates "test"
-- instead, and a tagged entry only runs while its context is active. Loading these in
-- tests would break every count assertion that expects to see nothing but what the test
-- itself created: OrderApiIntegrationTest alone expects 0, 1 and 2 rows in three places,
-- and two of the rows below are bob@example.com, whom those tests also use.
--
-- An untagged entry (001) runs in both. And dropping the contexts property altogether
-- would NOT exclude this one: with no runtime context set at all, Liquibase runs
-- everything, tagged or not.
--
-- Mind the prose in this file. A comment line whose first word after the dashes is one of
-- the directive keywords -- changeset, rollback, include, property, preconditions -- is
-- read as a malformed directive, and the build dies with "Unexpected formatting in
-- formatted changelog ... at line N". Keeping such a word off the start of a line is
-- enough; mid-sentence, as here, it parses fine.
--
-- No id column on purpose. H2 does not advance a `generated by default as identity` base
-- when a value is supplied, so spelling out ids 1..10 would leave the next generated id at
-- 1 and the first POST /orders would fail on a primary key violation. Letting the identity
-- assign them leaves the sequence at 11.
--
-- status and version are set explicitly because both columns are NOT NULL and these
-- inserts bypass the application: status is normally server-set to NEW by OrderService,
-- and version is normally Hibernate's to manage.
--
-- The two CANCELLED rows carry cancelled_at and cancellation_reason, which is the shape
-- OrderService.cancel leaves behind; the other statuses leave both null.
