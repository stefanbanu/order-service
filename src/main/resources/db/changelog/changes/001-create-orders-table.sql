--comment: Create the orders table, mirroring entity/Order
-- The table is "orders", not "order": ORDER is a SQL reserved word and H2 rejects
-- create table order (...) with a syntax error.
--
-- Column types were taken from the DDL Hibernate's ddl-auto used to generate for
-- entity/Order, with two deliberate differences:
--   * status is a plain varchar(16) rather than H2's native enum (...) type.
--     @Column(length = 16) on the entity asks for a varchar; the enum type is an H2
--     extension Hibernate reaches for on its own, and it would not survive a port.
--   * columns are declared in entity order, not Hibernate's alphabetical order.
-- The first is why application.yaml sets ddl-auto to `none` and not `validate`: Hibernate
-- would describe its own preferred type for that column and report a mismatch.
--
-- There is deliberately NO check constraint on status, tempting as `status in ('NEW', ...)`
-- looks. Added here, it parses and appears correctly in INFORMATION_SCHEMA, but inside a
-- @DataJpaTest slice every insert then fails with "Check constraint invalid:
-- CK_ORDERS_STATUS" -- H2 error 23514, meaning the constraint could not be evaluated,
-- whose swallowed cause is "The database has been closed [90098]". The stored expression
-- goes stale against that slice's embedded database; dropping and re-adding the identical
-- constraint at runtime makes the same insert succeed. The same changelog is fine in the
-- app and under @SpringBootTest, so this only shows up in the repository tests.
-- The set of legal values is enforced by OrderStatus and the transition matrix anyway.
--
-- Adding a field to entity/Order now means adding a changeset here too -- nothing creates
-- the column on your behalf any more.
create table orders (
    id                  bigint generated by default as identity,
    customer_email      varchar(255) not null,
    -- Money is numeric(19,2), never a float type. OrderRequest's
    -- @Digits(integer = 17, fraction = 2) is the matching guard at the API edge.
    amount              numeric(19, 2) not null,
    status              varchar(16) not null,
    created_at          timestamp(6) with time zone not null,
    -- @Version. NOT NULL DEFAULT 0 because Hibernate reads a null version as a transient
    -- entity and tries to INSERT it.
    version             bigint default 0 not null,
    cancelled_at        timestamp(6) with time zone,
    cancellation_reason varchar(255),
    constraint pk_orders primary key (id)
);
--rollback drop table orders;
